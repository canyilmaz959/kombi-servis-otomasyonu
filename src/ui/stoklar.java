    private void silbutonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_silbutonActionPerformed
        if (this.seciliStokId == -1) {
            JOptionPane.showMessageDialog(this, "Lütfen silmek istediğiniz ürünü tablodan seçin!", "Uyarı", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int onay = JOptionPane.showConfirmDialog(this, "Bu stok kaydını tamamen silmek istediğinize emin misiniz?", "Silme Onayı", JOptionPane.YES_NO_OPTION);
        if (onay == JOptionPane.YES_OPTION) {
            dao.stoklarDAO dao = new dao.stoklarDAO();
            if (dao.sil(this.seciliStokId)) {
                JOptionPane.showMessageDialog(this, "Ürün stok listesinden tamamen kaldırıldı.");
                tabloyuDoldur(); 
                formuTemizle();
            } else {
                JOptionPane.showMessageDialog(this, "Silme işlemi sırasında veritabanı hatası oluştu!", "Hata", JOptionPane.ERROR_MESSAGE);
            }
        }
    
    }//GEN-LAST:event_silbutonActionPerformed

    private void guncellebutonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guncellebutonActionPerformed
      if (this.seciliStokId == -1) {
        JOptionPane.showMessageDialog(this, "Lütfen güncelleme yapmak için tablodan bir satır seçin!", "Uyarı", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        int yeniMiktar = Integer.parseInt(stokguncellefield.getText().trim());
        if (yeniMiktar < 0) throw new NumberFormatException();
        
        String yeniSeriNo = serinofield.getText().trim();
        String yeniDurum = durumubox.getSelectedItem().toString(); 
        String yeniKategori = kombiguncelleR.isSelected() ? "kombi" : "parca"; 

        dao.stoklarDAO dao = new dao.stoklarDAO();
        if (dao.StokGuncelle(this.seciliStokId, yeniKategori, yeniSeriNo, yeniDurum, yeniMiktar)) {
            JOptionPane.showMessageDialog(this, "Stok bilgileri başarıyla güncellendi.");
            tabloyuDoldur(); 
            formuTemizle();
        } else {
            JOptionPane.showMessageDialog(this, "Güncelleme başarısız oldu.", "Hata", JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Lütfen geçerli bir adet sayısı giriniz!", "Hata", JOptionPane.ERROR_MESSAGE);
    }      
    }//GEN-LAST:event_guncellebutonActionPerformed

    private void stokeklebutonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_stokeklebutonActionPerformed
       String markaVerisi = stokmarkasi.getText().trim();
        String modelVerisi = stokmodelifield.getText().trim();
        String seriNoVerisi = stokserinofield.getText().trim();
        String durumVerisi = ekledurumubox.getSelectedItem().toString();
        String parcaIsmi = parcaismifield.getText().trim();
        
        String kategoriVerisi = turkombiR.isSelected() ? "kombi" : "parca";

        if (markaVerisi.isEmpty() || modelVerisi.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Marka ve Model alanları boş bırakılamaz!", "Uyarı", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int miktarVerisi = 0;
        try {
            miktarVerisi = Integer.parseInt(mevcutadetfield.getText().trim());
            if (miktarVerisi < 0) throw new NumberFormatException();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Lütfen geçerli bir adet sayısı giriniz!", "Hata", JOptionPane.ERROR_MESSAGE);
            return;
        }

        model.Stok yeniStok = new model.Stok();
        yeniStok.setMarka(markaVerisi);
        yeniStok.setModel(modelVerisi);
        yeniStok.setSeriNo(seriNoVerisi.isEmpty() ? null : seriNoVerisi);
        yeniStok.setKategori(kategoriVerisi);
        yeniStok.setMiktar(miktarVerisi); 
        yeniStok.setParcaAdi(parcaIsmi.isEmpty() ? (kategoriVerisi + " - " + markaVerisi + " " + modelVerisi) : parcaIsmi);
        yeniStok.setMinStok(0);
        yeniStok.setBirimFiyat(0.0);
        yeniStok.setTedarikci(durumVerisi); 
        int rastgeleSayi = (int)(Math.random() * 9000) + 1000;
        String otomatikKod = "PRK-" + rastgeleSayi;
        yeniStok.setParcaKodu(otomatikKod);

        dao.stoklarDAO dao = new dao.stoklarDAO();
        if (dao.ekle(yeniStok)) {
            JOptionPane.showMessageDialog(this, "Stok veritabanına başarıyla eklendi.");
            tabloyuDoldur(); 
            formuTemizle();
        } else {
            JOptionPane.showMessageDialog(this, "Stok ekleme işlemi başarısız!", "Sistem Hatası", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_stokeklebutonActionPerformed
private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {
        int seciliSatir = jTable1.getSelectedRow();
    if (seciliSatir != -1) {
        this.seciliStokId = Integer.parseInt(jTable1.getValueAt(seciliSatir, 0).toString());
        String parcaAdi = jTable1.getValueAt(seciliSatir, 1).toString();
        String kategori = jTable1.getValueAt(seciliSatir, 2).toString();
        String marka = jTable1.getValueAt(seciliSatir, 3).toString();
        String model = jTable1.getValueAt(seciliSatir, 4).toString();
        String seriNo = jTable1.getValueAt(seciliSatir, 5).toString();
        String miktar = jTable1.getValueAt(seciliSatir, 6).toString();
        String durum = jTable1.getValueAt(seciliSatir, 7).toString();

        parcaismifield.setText(parcaAdi.equals("-") ? "" : parcaAdi);
        stokmarkasi.setText(marka);
        stokmodelifield.setText(model);
        stokserinofield.setText(seriNo.equals("-") ? "" : seriNo);
        mevcutadetfield.setText(miktar);
        if (!durum.equals("-")) {
            ekledurumubox.setSelectedItem(durum);
        } else {
            ekledurumubox.setSelectedIndex(0);
        }

        stokguncellefield.setText(miktar);
        serinofield.setText(seriNo.equals("-") ? "" : seriNo);
        guncelparcafield.setText(parcaAdi.equals("-") ? "" : parcaAdi);
        guncelmodelfield.setText(model.equals("-") ? "" : model);
        guncelmarkafield.setText(marka.equals("-") ? "" : marka);
        
        
        if (!durum.equals("-")) {
            durumubox.setSelectedItem(durum);
        } else {
            durumubox.setSelectedIndex(0);
        }

        if (kategori.equalsIgnoreCase("kombi")) {
            turkombiR.setSelected(true);
            kombiguncelleR.setSelected(true);
        } else {
            turparcaR.setSelected(true);
            parcaguncelleR.setSelected(true);
        }
    }
    }

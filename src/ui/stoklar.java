    public void tabloyuDoldur() {
        String[] kolonlar = {"ID", "Parça İsmi", "Kategori", "Marka", "Model", "Seri No", "Miktar", "Durum"};
        DefaultTableModel model = new DefaultTableModel(kolonlar, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; 
            }
        };

        try {
            dao.stoklarDAO dao = new dao.stoklarDAO();
            List<model.Stok> liste = dao.tumStok();

            if (liste != null) {
                for (model.Stok s : liste) {
                    Object[] satir = {
                        s.getId(),
                        s.getParcaAdi() == null ? "-" : s.getParcaAdi(),
                        s.getKategori(),
                        s.getMarka(),
                        s.getModel(),
                        s.getSeriNo() == null ? "-" : s.getSeriNo(),
                        s.getMiktar(),
                        s.getTedarikci() == null ? "-" : s.getTedarikci() // formdaki durumufield'ı buraya bağlıyoruz
                    };
                    model.addRow(satir);
                }
            }
        } catch (Exception e) {
            System.out.println("Tablo yüklenirken hata oluştu: " + e.getMessage());
        }

        jTable1.setModel(model);
    }


       private void musteriTablosunuDoldur() {
        String[] kolonlar = {"ID", "Ad", "Soyad", "Telefon", "E-mail", "Adres 1", "Adres 2"};
        DefaultTableModel model = new DefaultTableModel(kolonlar, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; 
            }
        };

        try {
            List<Musteri> silinenler = mDao.silinmisMusteriler();

            if (silinenler != null) {
                for (Musteri m : silinenler) {
                    Object[] satir = {
                        m.getId(), 
                        m.getAd(), 
                        m.getSoyad(), 
                        m.getTelefon(), 
                        m.getEmail() == null ? "-" : m.getEmail(), 
                        m.getAdres1() == null ? "-" : m.getAdres1(), 
                        m.getAdres2() == null ? "-" : m.getAdres2() 
                    };
                    model.addRow(satir);
                }
            }
        } catch (Exception e) {
            System.out.println("Müşteri geçmiş tablosu yüklenirken hata: " + e.getMessage());
        }

        jTable1.setModel(model);
    }
       
       private void personelTablosunuDoldur() {
        String[] kolonlar = {"ID", "Ad Soyad", "Kullanıcı Adı", "Ünvan", "T.C. No", "Mezuniyet"};
        DefaultTableModel model = new DefaultTableModel(kolonlar, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; 
            }
        };

        try {
            List<Kullanici> silinenler = kDao.silinmisPersoneller();

            if (silinenler != null) {
                for (Kullanici k : silinenler) {
                    Object[] satir = {
                        k.getId(),
                        k.getAdSoyad(),
                        k.getKullaniciAdi(),
                        k.getRol(),
                        k.getTcNo() == null ? "-" : k.getTcNo(),
                        k.getMezuniyet() == null ? "-" : k.getMezuniyet()
                    };
                    model.addRow(satir);
                }
            }
        } catch (Exception e) {
            System.out.println("Personel geçmiş tablosu yüklenirken hata: " + e.getMessage());
        }

        jTable4.setModel(model);
    }


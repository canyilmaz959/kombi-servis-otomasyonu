    private void btnGeriYukleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGeriYukleActionPerformed
        int aktifSekme = jTabbedPane2.getSelectedIndex(); 

        if (aktifSekme == 0) {
            int seciliSatir = jTable1.getSelectedRow();
            if (seciliSatir == -1) {
                JOptionPane.showMessageDialog(this, "Lütfen geri yüklemek istediğiniz müşteriyi tablodan seçin!", "Uyarı", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int seciliMusteriId = Integer.parseInt(jTable1.getValueAt(seciliSatir, 0).toString());
            String musteriAdSoyad = jTable1.getValueAt(seciliSatir, 1).toString() + " " + jTable1.getValueAt(seciliSatir, 2).toString();

            int onay = JOptionPane.showConfirmDialog(this, 
                musteriAdSoyad + " isimli müşteriyi tekrar aktif kayıtlar arasına taşımak istiyor musunuz?", 
                "Geri Yükleme Onayı", JOptionPane.YES_NO_OPTION);

            if (onay == JOptionPane.YES_OPTION) {
                if (mDao.geriYukle(seciliMusteriId)) {
                    JOptionPane.showMessageDialog(this, "Müşteri başarıyla geri yüklendi ve aktif listeye eklendi.");
                    tabloyuDoldur(); 
                } else {
                    JOptionPane.showMessageDialog(this, "Geri yükleme işlemi sırasında veritabanı hatası oluştu!", "Hata", JOptionPane.ERROR_MESSAGE);
                }
            }
        } 
        else if (aktifSekme == 1) {
            int seciliSatir = jTable4.getSelectedRow();
            if (seciliSatir == -1) {
                JOptionPane.showMessageDialog(this, "Lütfen işe geri alacağınız personeli tablodan seçin!", "Uyarı", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int seciliPersonelId = Integer.parseInt(jTable4.getValueAt(seciliSatir, 0).toString());
            String personelAdSoyad = jTable4.getValueAt(seciliSatir, 1).toString();

            int onay = JOptionPane.showConfirmDialog(this, 
                personelAdSoyad + " personeli yeniden işe alınsın ve giriş yetkisi aktifleştirilsin mi?", 
                "Personel Geri Yükle", JOptionPane.YES_NO_OPTION);

            if (onay == JOptionPane.YES_OPTION) {
                if (kDao.sil(seciliPersonelId)) { 
                    String sql = "UPDATE kullanici SET durum = 'Aktif' WHERE id = ?";
                    try {
                        java.sql.PreparedStatement ps = util.DBconnection.getConnection().prepareStatement(sql);
                        ps.setInt(1, seciliPersonelId);
                        if (ps.executeUpdate() > 0) {
                            JOptionPane.showMessageDialog(this, "Personel başarıyla işe geri alındı, sisteme giriş yetkisi açıldı.");
                            tabloyuDoldur();
                        }
                    } catch (Exception e) {
                        System.out.println("Geri yükleme SQL hatası: " + e.getMessage());
                    }
                }
            }
        }
    }//GEN-LAST:event_btnGeriYukleActionPerformed

